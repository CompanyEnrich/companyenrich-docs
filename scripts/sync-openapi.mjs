import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Endpoint pages and their navigation are generated. Edit the API's source
// descriptions upstream; keep hand-written guides outside these directories.
process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const check = process.argv.includes('--check');
const methods = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace']);
const config = JSON.parse(await readFile('docs.json', 'utf8'));
const generatedMarker = '{/* Generated by npm run sync:openapi. */}';
const versions = ['v2', 'v1'];
const inputs = await Promise.all(versions.map(async (version) => {
  const file = `openapi/${version}.json`;
  let text;
  if (check) {
    text = await readFile(file, 'utf8');
  } else {
    const response = await fetch(`https://api.companyenrich.com/${file}`, {
      signal: AbortSignal.timeout(30_000),
    });
    if (!response.ok) throw new Error(`${file}: HTTP ${response.status}`);
    text = await response.text();
  }
  const spec = JSON.parse(text);
  if (!spec.openapi?.startsWith('3.') || !Object.keys(spec.paths ?? {}).length) {
    throw new Error(`${file}: expected a nonempty OpenAPI 3 specification`);
  }
  // Fail before writing if a downloaded specification has dangling references.
  function validateRefs(value) {
    if (!value || typeof value !== 'object') return;
    if (typeof value.$ref === 'string') {
      if (!value.$ref.startsWith('#/')) throw new Error(`${file}: external reference ${value.$ref}`);
      const target = value.$ref.slice(2).split('/').reduce((node, part) =>
        node?.[part.replace(/~1/g, '/').replace(/~0/g, '~')], spec);
      if (target === undefined) throw new Error(`${file}: unresolved ${value.$ref}`);
    }
    Object.values(value).forEach(validateRefs);
  }
  validateRefs(spec);
  return { version, file, text, spec };
}));

let total = 0;
for (const { version, file, text, spec } of inputs) {
  const directory = `api-reference/${version}`;
  const pages = new Map();
  const groups = new Map();
  for (const [path, operations] of Object.entries(spec.paths)) {
    for (const [method, operation] of Object.entries(operations)) {
      if (!methods.has(method)) continue;
      const oldSlug = `${method}_${path.slice(1).replaceAll('/', '-').replace(/[{}]/g, '').toLowerCase()}`;
      const slug = `${method}-${path.replace(/^\/v2\//, '/').slice(1).replaceAll('/', '-').replace(/[{}]/g, '').toLowerCase()}`;
      const page = `${directory}/${slug}`;
      if (pages.has(page)) throw new Error(`Duplicate endpoint page: ${page}`);
      pages.set(page, `---\ntitle: ${JSON.stringify(operation.summary || `${method.toUpperCase()} ${path}`)}\nopenapi: ${JSON.stringify(`/${file} ${method.toUpperCase()} ${path}`)}\n---\n\n${generatedMarker}\n`);
      const tag = (operation.tags?.[0] ?? 'Endpoints').replace(' / ', ' · ');
      if (!groups.has(tag)) groups.set(tag, []);
      groups.get(tag).push(page);
      const sources = [`/reference/${oldSlug}`];
      if (version === 'v1') sources.push(`/v1.0/reference/${oldSlug}`);
      for (const source of sources) {
        const redirect = config.redirects.find((entry) => entry.source === source);
        const destination = `/${page}`;
        if (check && redirect?.destination !== destination) {
          throw new Error(`${source}: redirect is out of sync; run npm run sync:openapi`);
        }
        if (redirect) redirect.destination = destination;
        else config.redirects.push({ source, destination });
      }
    }
  }
  const tab = config.navigation.tabs.find((entry) => entry.tab === `API ${version.toUpperCase()}`);
  if (!tab) throw new Error(`Missing API ${version.toUpperCase()} tab in docs.json`);
  const navigation = [
    { group: 'Overview', pages: [`${directory}/overview`] },
    ...Array.from(groups, ([group, pages]) => ({ group, pages })),
  ];
  if (check) {
    if (JSON.stringify(tab.groups) !== JSON.stringify(navigation)) {
      throw new Error(`${version}: navigation is out of sync; run npm run sync:openapi`);
    }
  } else {
    await mkdir('openapi', { recursive: true });
    await mkdir(directory, { recursive: true });
    await writeFile(file, text);
    tab.groups = navigation;
  }
  for (const [page, content] of pages) {
    if (check) {
      if (await readFile(`${page}.mdx`, 'utf8') !== content) {
        throw new Error(`${page}: generated page is out of sync`);
      }
    } else {
      await writeFile(`${page}.mdx`, content);
    }
  }
  for (const filename of await readdir(directory)) {
    if (!filename.endsWith('.mdx') || pages.has(`${directory}/${filename.slice(0, -4)}`)) continue;
    const oldFile = `${directory}/${filename}`;
    if (!(await readFile(oldFile, 'utf8')).includes(generatedMarker)) continue;
    if (check) throw new Error(`Stale generated page: ${oldFile}`);
    await unlink(oldFile);
    config.redirects = config.redirects.filter((redirect) => redirect.destination !== `/${oldFile.slice(0, -4)}`);
  }
  total += pages.size;
  console.log(`${version}: ${pages.size} endpoint pages ${check ? 'verified' : 'updated'}`);
}
if (!check) await writeFile('docs.json', `${JSON.stringify(config, null, 2)}\n`);
console.log(`${total} endpoints total. Specifications are preserved as published, including authentication.`);
